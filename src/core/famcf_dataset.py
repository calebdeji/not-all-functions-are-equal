"""
famcf_dataset.py

Feature extraction and dataset utilities for FAMCF.


FAMCFDataset      : pre-encoded features.pkl produced by extract_famcf_features.py
                        (supports permission, api_call, and opcode feature types)

Family splits use seed=42, matching extract_flat_dataset_splits in utils.py exactly.
"""

import os
import pickle

import numpy as np
import pandas as pd
import torch
from torch.utils.data import Dataset




def get_family_splits(csv_path, n_way=5, seed=42):
    """
    Identical split logic to Utils.extract_flat_dataset_splits (seed=42).
    Returns (train_families, val_families, test_families) as sets of family names.
    """
    df = pd.read_csv(csv_path)
    unique_families = sorted(df["family"].unique().tolist())
    num_families = len(unique_families)

    perm = torch.randperm(
        num_families, generator=torch.Generator().manual_seed(seed)
    ).tolist()
    shuffled = [unique_families[i] for i in perm]

    val_size = max(n_way, int(0.2 * num_families))
    test_size = max(n_way, int(0.2 * num_families))
    train_end = num_families - val_size - test_size
    val_end = train_end + val_size

    return (
        set(shuffled[:train_end]),
        set(shuffled[train_end:val_end]),
        set(shuffled[val_end:]),
    )


def build_vocabulary(hashes, feature_dir):
    """
    Build permission and api_call vocabularies from a list of sample hashes.
    Should be called only on training-split hashes to avoid leakage.
    Returns (perm_vocab, api_vocab) as sorted lists of feature strings.
    """
    perm_vocab = set()
    api_vocab = set()

    for h in hashes:
        fpath = os.path.join(feature_dir, h)
        if not os.path.exists(fpath):
            continue
        with open(fpath) as f:
            for line in f:
                line = line.strip()
                if line.startswith("permission::"):
                    perm_vocab.add(line)
                elif line.startswith("api_call::"):
                    api_vocab.add(line)

    return sorted(perm_vocab), sorted(api_vocab)




class FAMCFDataset(Dataset):
    """
    Dataset backed by features.pkl produced by extract_famcf_features.py.

    Supports all three feature types: permission, api_call, opcode.
    Each sample returns (perm_vec, api_vec, opc_vec, label).

    family_to_idx : {family_name: int} loaded from family_to_idx.json
                    (generated by run_extract_features.sh). Indices are
                    consistent with the graph dataset for the same corpus.
    """

    def __init__(self, samples_csv: str, features_pkl: str, families: set,
                 family_to_idx: dict, hash_filter: set = None):
        df = pd.read_csv(samples_csv)
        df["family"] = df["family"].str.lower().str.strip()
        df = df[df["family"].isin(families)].reset_index(drop=True)

        self.family_to_idx = family_to_idx

        with open(features_pkl, "rb") as f:
            all_features = pickle.load(f)

        hash_col = "sha256" if "sha256" in df.columns else "hash"
        if hash_filter is not None:
            df = df[df[hash_col].isin(hash_filter)].reset_index(drop=True)

        self.samples = []
        self.labels  = []
        perm_list, api_list, opc_list = [], [], []

        for _, row in df.iterrows():
            sha = row[hash_col]
            if sha not in all_features:
                continue
            entry = all_features[sha]
            self.samples.append(sha)
            self.labels.append(self.family_to_idx[row["family"]])
            perm_list.append(entry["perm_vec"])
            api_list.append(entry["api_vec"])
            opc_list.append(entry["opc_vec"])

        self.perm_vecs = np.stack(perm_list).astype(np.float32)
        self.api_vecs  = np.stack(api_list).astype(np.float32)
        self.opc_vecs  = np.stack(opc_list).astype(np.float32)

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        return (
            torch.tensor(self.perm_vecs[idx]),
            torch.tensor(self.api_vecs[idx]),
            torch.tensor(self.opc_vecs[idx]),
            self.labels[idx],
        )

    def get_labels(self):
        return self.labels

    def get_all_features(self, feature_type: str) -> torch.Tensor:
        if feature_type == "permission":
            return torch.tensor(self.perm_vecs)
        elif feature_type == "api_call":
            return torch.tensor(self.api_vecs)
        elif feature_type == "opcode":
            return torch.tensor(self.opc_vecs)
        else:
            raise ValueError(f"Unknown feature_type: {feature_type}")
